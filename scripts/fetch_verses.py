def fetch(ref: str, tr: str) -> dict:
    url = API.format(ref=urllib.parse.quote(ref), tr=tr)
    for attempt in range(5):
        try:
            with urllib.request.urlopen(url, timeout=20) as r:
                return json.load(r)
        except Exception as e:  # rate limit or network blip: back off and retry
            print(f"  retry {ref} {tr}: {e}")
            time.sleep(8 * (attempt + 1))
    raise SystemExit(f"Could not fetch {ref} ({tr})")


def clean(t: str) -> str:
    return " ".join(t.split())


def existing() -> dict:
    """Reuse verses already fetched so adding a reference only downloads the new one."""
    if not OUT.exists():
        return {}
    body = OUT.read_text().split("export const VERSES = ", 1)[1].rstrip().rstrip(";")
    return {v["ref"]: v for v in json.loads(body)}


def main() -> None:
    have, verses = existing(), []
    for ref, theme in REFS:
        if ref in have and all(have[ref]["text"].get(t) for t in TRANSLATIONS):
            verses.append({**have[ref], "theme": theme})
            continue
        item = {"ref": ref, "theme": theme, "text": {}}
        for tr in TRANSLATIONS:
            data = fetch(ref, tr)
            item["text"][tr] = clean(" ".join(v["text"] for v in data["verses"]))
            time.sleep(2.2)
        verses.append(item)
        print(f"{ref:24} ok")
    body = json.dumps(verses, indent=1, ensure_ascii=False)
    OUT.write_text(
        "// GENERATED by scripts/fetch_verses.py from bible-api.com. Do not edit by hand.\n"
        "// KJV and WEB are public domain.\n"
        f"export const TRANSLATIONS = {json.dumps(TRANSLATIONS)};\n"
        f"export const VERSES = {body};\n"
    )
    print(f"wrote {len(verses)} verses -> {OUT}")


if __name__ == "__main__":
    main()
